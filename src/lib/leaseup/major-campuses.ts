const COLS = "id, name, short_name, city, state, lat, lng, domain, slug, level";

/** Fetch the curated major-school rows. Returns [] on failure — the directory
 *  still renders the campuses that have listings. */
export async function fetchMajorCampuses(): Promise<Campus[]> {
  const { data, error } = await supabase.from("campuses").select(COLS).in("slug", MAJOR_CAMPUS_SLUGS);
  if (error) return [];
  return (data ?? []) as Campus[];
}
